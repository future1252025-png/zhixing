import { createApp, defineComponent, h, nextTick, ref } from 'vue'

import { isAMapConfigured, loadAMapPlugin, loadAMapSdk } from '@/utils/amap'
import { MAP_DRAG_HOLD_DELAY_MS } from '@/utils/mapInteraction'
import RealCampusMap from './RealCampusMap.vue'


vi.mock('@/utils/amap', () => ({
  isAMapConfigured: vi.fn(),
  loadAMapSdk: vi.fn(),
  loadAMapPlugin: vi.fn()
}))


type Deferred<T> = {
  promise: Promise<T>
  resolve: (value: T) => void
}

function deferred<T>(): Deferred<T> {
  let resolve!: (value: T) => void
  const promise = new Promise<T>((resolver) => {
    resolve = resolver
  })
  return { promise, resolve }
}

async function settle(): Promise<void> {
  await Promise.resolve()
  await Promise.resolve()
  await nextTick()
}

function dispatchPointer(
  target: Element,
  type: string,
  values: { pointerId: number; pointerType: string; clientX: number; clientY: number }
): void {
  const event = new Event(type, { bubbles: true, cancelable: true })
  Object.defineProperties(event, {
    pointerId: { value: values.pointerId },
    pointerType: { value: values.pointerType },
    clientX: { value: values.clientX },
    clientY: { value: values.clientY }
  })
  target.dispatchEvent(event)
}


describe('RealCampusMap async lifecycle', () => {
  let host: HTMLDivElement

  beforeEach(() => {
    vi.mocked(isAMapConfigured).mockReturnValue(true)
    host = document.createElement('div')
    document.body.append(host)
  })

  afterEach(() => {
    host.remove()
    vi.clearAllMocks()
  })

  it('does not construct a map when the SDK resolves after unmount', async () => {
    const sdk = deferred<any>()
    const MapConstructor = vi.fn(function FakeMap() {})
    vi.mocked(loadAMapSdk).mockReturnValue(sdk.promise)

    const application = createApp(RealCampusMap)
    application.mount(host)
    await nextTick()
    application.unmount()

    sdk.resolve({ Map: MapConstructor })
    await settle()

    expect(MapConstructor).not.toHaveBeenCalled()
    expect(loadAMapPlugin).not.toHaveBeenCalled()
  })

  it('destroys map state and ignores controls that finish loading after unmount', async () => {
    const controls = deferred<any>()
    const marker = { on: vi.fn() }
    const routePlanner = { search: vi.fn(), clear: vi.fn() }
    const mapInstance = {
      add: vi.fn(),
      remove: vi.fn(),
      addControl: vi.fn(),
      on: vi.fn(),
      off: vi.fn(),
      getZoom: vi.fn(() => 16),
      setFitView: vi.fn(),
      destroy: vi.fn()
    }
    const amap = {
      Map: vi.fn(function FakeMap() {
        return mapInstance
      }),
      Marker: vi.fn(function FakeMarker() {
        return marker
      }),
      Walking: vi.fn(function FakeWalking() {
        return routePlanner
      }),
      Scale: vi.fn(),
      ToolBar: vi.fn()
    }
    vi.mocked(loadAMapSdk).mockResolvedValue(amap)
    vi.mocked(loadAMapPlugin).mockImplementation((name) => {
      if (name === 'AMap.Walking') return Promise.resolve(amap)
      return controls.promise
    })

    const application = createApp(RealCampusMap, {
      buildings: [{
        id: 1,
        name: '教学楼',
        type: '教学楼',
        description: '',
        latitude: 30.59,
        longitude: 114.33,
        map_x: 0,
        map_y: 0,
        walk_hint: null
      }],
      fromPoint: { name: '图书馆', latitude: 30.58, longitude: 114.32 },
      toPoint: { name: '教学楼', latitude: 30.59, longitude: 114.33 },
      walkingRoute: true
    })
    application.mount(host)
    await settle()
    await settle()

    expect(amap.Map).toHaveBeenCalledOnce()
    expect(routePlanner.search).toHaveBeenCalledOnce()
    application.unmount()

    expect(routePlanner.clear).toHaveBeenCalledOnce()
    expect(mapInstance.remove).toHaveBeenCalled()
    expect(mapInstance.off).toHaveBeenCalled()
    expect(mapInstance.destroy).toHaveBeenCalledOnce()

    controls.resolve(amap)
    await settle()
    expect(mapInstance.addControl).not.toHaveBeenCalled()
  })

  it('adds accessible names to frames and images generated by the map SDK', async () => {
    const mapInstance = {
      add: vi.fn(),
      remove: vi.fn(),
      addControl: vi.fn(),
      on: vi.fn(),
      off: vi.fn(),
      getZoom: vi.fn(() => 16),
      setFitView: vi.fn(),
      destroy: vi.fn()
    }
    const amap = {
      Map: vi.fn(function FakeMap(container: HTMLElement) {
        const frame = document.createElement('iframe')
        const logo = document.createElement('a')
        logo.className = 'amap-logo'
        logo.append(document.createElement('img'))
        const tile = document.createElement('img')
        container.append(frame, logo, tile)
        return mapInstance
      }),
      Marker: vi.fn(),
      Scale: vi.fn(),
      ToolBar: vi.fn()
    }
    vi.mocked(loadAMapSdk).mockResolvedValue(amap)
    vi.mocked(loadAMapPlugin).mockResolvedValue(amap)

    const application = createApp(RealCampusMap, { title: '路线地图' })
    application.mount(host)
    await settle()

    expect(host.querySelector('iframe')?.title).toBe('路线地图交互辅助框架')
    expect(host.querySelector('.amap-logo img')?.getAttribute('alt')).toBe('高德地图')
    expect(host.querySelectorAll('img')[1]?.getAttribute('alt')).toBe('')

    application.unmount()
  })

  it('rebuilds markers without moving the view when only the active building changes', async () => {
    const marker = { on: vi.fn() }
    const mapInstance = {
      add: vi.fn(),
      remove: vi.fn(),
      addControl: vi.fn(),
      on: vi.fn(),
      off: vi.fn(),
      // 建筑层级 zoom：普通 pin 只在 >=17.5 显示，本测试关注的是标记重建不动视角
      getZoom: vi.fn(() => 18),
      setFitView: vi.fn(),
      setCenter: vi.fn(),
      destroy: vi.fn()
    }
    const amap = {
      Map: vi.fn(function FakeMap() {
        return mapInstance
      }),
      Marker: vi.fn(function FakeMarker() {
        return marker
      }),
      Scale: vi.fn(),
      ToolBar: vi.fn()
    }
    vi.mocked(loadAMapSdk).mockResolvedValue(amap)
    vi.mocked(loadAMapPlugin).mockResolvedValue(amap)

    const building = {
      id: 1,
      name: '教学楼',
      type: '教学楼',
      description: '',
      latitude: 30.59,
      longitude: 114.33,
      map_x: 0,
      map_y: 0,
      walk_hint: null
    }
    const buildings = ref([building])
    const activeBuildingId = ref<number | null>(null)
    const Host = defineComponent({
      render() {
        return h(RealCampusMap, {
          buildings: buildings.value,
          activeBuildingId: activeBuildingId.value
        })
      }
    })
    const application = createApp(Host)
    application.mount(host)
    await settle()

    expect(mapInstance.add).toHaveBeenCalledTimes(1)
    expect(mapInstance.setFitView).toHaveBeenCalledTimes(1)

    activeBuildingId.value = 1
    await settle()

    expect(mapInstance.add).toHaveBeenCalledTimes(2)
    expect(mapInstance.setFitView).toHaveBeenCalledTimes(1)
    expect(mapInstance.setCenter).not.toHaveBeenCalled()

    buildings.value = [...buildings.value, { ...building, id: 2, name: '图书馆', latitude: 30.6 }]
    await settle()

    expect(mapInstance.add).toHaveBeenCalledTimes(3)
    expect(mapInstance.setFitView).toHaveBeenCalledTimes(2)

    application.unmount()
  })

  it('reveals ordinary pins only after zoomend crosses into building level', async () => {
    const marker = { on: vi.fn() }
    let zoom = 16
    const listeners: Record<string, () => void> = {}
    const mapInstance = {
      add: vi.fn(),
      remove: vi.fn(),
      addControl: vi.fn(),
      on: vi.fn((event: string, handler: () => void) => {
        listeners[event] = handler
      }),
      off: vi.fn(),
      getZoom: vi.fn(() => zoom),
      setFitView: vi.fn(),
      setCenter: vi.fn(),
      destroy: vi.fn()
    }
    const amap = {
      Map: vi.fn(function FakeMap() {
        return mapInstance
      }),
      Marker: vi.fn(function FakeMarker() {
        return marker
      }),
      Scale: vi.fn(),
      ToolBar: vi.fn()
    }
    vi.mocked(loadAMapSdk).mockResolvedValue(amap)
    vi.mocked(loadAMapPlugin).mockResolvedValue(amap)

    const building = {
      id: 1,
      name: '教学楼',
      type: '教学楼',
      description: '',
      latitude: 30.59,
      longitude: 114.33,
      map_x: 0,
      map_y: 0,
      walk_hint: null
    }
    const application = createApp(defineComponent({
      render() {
        return h(RealCampusMap, { buildings: [building] })
      }
    }))
    application.mount(host)
    await settle()

    // mixed 档位（zoom 16）：普通 pin 隐藏，不构造任何标记
    expect(amap.Marker).not.toHaveBeenCalled()

    zoom = 18
    listeners.zoomend?.()
    await settle()

    // 跨入 building 档位：zoomend 驱动重建，普通 pin 出现
    expect(amap.Marker).toHaveBeenCalledTimes(1)
    expect(mapInstance.add).toHaveBeenCalledTimes(1)

    application.unmount()
  })

  it('requires a steady touch hold before manually panning the map', async () => {
    vi.useFakeTimers()
    const originalMatchMedia = window.matchMedia
    Object.defineProperty(window, 'matchMedia', {
      configurable: true,
      value: vi.fn(() => ({ matches: true }))
    })

    const mapInstance = {
      add: vi.fn(),
      remove: vi.fn(),
      addControl: vi.fn(),
      on: vi.fn(),
      off: vi.fn(),
      getZoom: vi.fn(() => 16),
      setCenter: vi.fn(),
      setStatus: vi.fn(),
      panBy: vi.fn(),
      destroy: vi.fn()
    }
    const amap = {
      Map: vi.fn(function FakeMap() {
        return mapInstance
      }),
      Marker: vi.fn(),
      Scale: vi.fn(),
      ToolBar: vi.fn()
    }
    vi.mocked(loadAMapSdk).mockResolvedValue(amap)
    vi.mocked(loadAMapPlugin).mockResolvedValue(amap)
    const application = createApp(RealCampusMap)

    try {
      application.mount(host)
      await settle()
      const container = host.querySelector('.real-map-container')!

      expect(amap.Map).toHaveBeenCalledWith(
        container,
        expect.objectContaining({ dragEnable: false })
      )
      dispatchPointer(container, 'pointerdown', {
        pointerId: 6,
        pointerType: 'mouse',
        clientX: 18,
        clientY: 28
      })
      expect(mapInstance.setStatus).toHaveBeenLastCalledWith({ dragEnable: true })
      dispatchPointer(container, 'pointerdown', {
        pointerId: 7,
        pointerType: 'touch',
        clientX: 20,
        clientY: 30
      })
      await nextTick()
      expect(mapInstance.setStatus).toHaveBeenLastCalledWith({ dragEnable: false })
      expect(host.textContent).toContain('继续按住以拖动地图')
      expect(mapInstance.panBy).not.toHaveBeenCalled()

      await vi.advanceTimersByTimeAsync(MAP_DRAG_HOLD_DELAY_MS)
      await nextTick()
      expect(host.textContent).toContain('现在可以拖动地图')
      dispatchPointer(container, 'pointermove', {
        pointerId: 7,
        pointerType: 'touch',
        clientX: 34,
        clientY: 38
      })
      expect(mapInstance.panBy).toHaveBeenCalledWith(14, 8, 0)

      dispatchPointer(container, 'pointerup', {
        pointerId: 7,
        pointerType: 'touch',
        clientX: 34,
        clientY: 38
      })
      await nextTick()
      expect(host.textContent).not.toContain('现在可以拖动地图')
      expect(mapInstance.setStatus).toHaveBeenLastCalledWith({ dragEnable: false })
    } finally {
      application.unmount()
      Object.defineProperty(window, 'matchMedia', {
        configurable: true,
        value: originalMatchMedia
      })
      vi.useRealTimers()
    }
  })
})
