import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('single-course and whole-day makeups agree with the timetable, home and reminders', async ({ page }, testInfo) => {
  await page.clock.setFixedTime(new Date('2026-09-19T13:00:00+08:00'))
  await page.addInitScript(() => {
    Object.defineProperty(window, 'Notification', { configurable: true, value: class { static permission = 'granted'; close() {} } })
  })
  const credentials = { student_id: `makeups-${testInfo.project.name}`, password: 'test-makeup-2026' }
  expect((await page.request.post('http://127.0.0.1:8010/api/auth/register', { data: { ...credentials, nickname: '补课测试' } })).ok()).toBe(true)
  const login = await page.request.post('http://127.0.0.1:8010/api/auth/login', { data: credentials })
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  expect((await page.request.put('http://127.0.0.1:8010/api/semester', { headers, data: { start_date: '2026-08-31', total_weeks: 20 } })).ok()).toBe(true)
  const originals: any[] = []
  for (const [course_name, start_time, end_time] of [['算法设计', '08:00', '09:40'], ['思想概论', '14:30', '16:10']]) {
    const result = await page.request.post('http://127.0.0.1:8010/api/courses', { headers, data: { course_name, weekday: 1,
      weeks: '1-16', start_time, end_time, building_id: 1, room_name: '409', teacher: '杨老师' } })
    expect(result.ok()).toBe(true)
    originals.push(await result.json())
  }
  expect((await page.request.put('http://127.0.0.1:8010/api/reminders', { headers,
    data: { revision: 0, course_settings: { enabled: true, lead_minutes: 10, mode: 'silent' }, items: [] } })).ok()).toBe(true)
  await page.goto('/courses')
  await expect(page.locator('#courseWeekSelect')).toHaveValue('3')
  await expect(page.locator('.timetable-week-stage')).toHaveCount(1)
  await page.locator('.timetable-week-stage[data-week="3"] .course-content').filter({ hasText: '思想概论' }).click()
  await page.getByText('添加补课', { exact: true }).click()
  await expect(page).toHaveURL(/\/courses\/makeups/)
  await expect(page.getByRole('button', { name: /思想概论.*星期一/ })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('思想概论上课时间', { exact: true })).toHaveValue('14:30')
  await expect(page.getByLabel('补课日期', { exact: true })).toHaveValue('2026-09-19')
  // A phone can be upgraded before its backend. Preserve the draft on the old
  // server's 405 and let the same form succeed once the endpoint is available.
  await page.route('**/api/courses/makeups', route => route.fulfill({
    status: 405, contentType: 'application/json', body: JSON.stringify({ detail: 'Method Not Allowed' })
  }), { times: 1 })
  await page.getByRole('button', { name: '添加 1 门补课', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('平板后端已更新')
  await expect(page.getByRole('alert')).toBeInViewport()
  await expect(page.getByLabel('思想概论上课时间', { exact: true })).toHaveValue('14:30')
  await expect(page.getByLabel('补课日期', { exact: true })).toHaveValue('2026-09-19')
  expect((await (await page.request.get('http://127.0.0.1:8010/api/courses', { headers })).json()).length).toBe(2)
  await page.getByRole('button', { name: '添加 1 门补课', exact: true }).click()
  await expect(page).toHaveURL(/\/courses\?week=3#current-week$/)
  await expect(page.locator('[data-makeup-date="2026-09-19"]')).toHaveCount(1)
  await expect(page.locator('.course-content').filter({ hasText: '思想概论' })).toHaveCount(2)
  await page.getByRole('link', { name: '校园', exact: true }).click()
  await expect(page.locator('.today-card')).toContainText('思想概论')
  await expect(page.locator('.today-card')).toContainText('14:30')
  await page.getByRole('link', { name: '提醒', exact: true }).click()
  await expect(page.locator('.next-reminders li')).toHaveCount(1)
  await expect(page.locator('.next-reminders li')).toContainText('14:20')

  // Canceling does not remove the original course; the batch editor remains concise.
  await page.getByRole('link', { name: '课表', exact: true }).click()
  await page.getByRole('button', { name: '补课', exact: true }).click()
  await page.locator('.makeup-manage summary').click()
  await page.getByRole('button', { name: '取消这次', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认取消', exact: true }).click()
  await expect(page.locator('.makeup-manage')).toHaveCount(0)
  await page.getByRole('button', { name: '按一天补课', exact: true }).click()
  await page.getByLabel('原上课日期', { exact: true }).fill('2026-09-14')
  await expect(page.locator('.makeup-row')).toHaveCount(2)
  await page.getByLabel('补课日期', { exact: true }).fill('2026-09-26')
  await page.getByLabel('原日期这几门课停课', { exact: true }).check()
  await page.getByLabel('思想概论上课时间', { exact: true }).fill('14:40')
  await page.getByLabel('思想概论下课时间', { exact: true }).fill('16:20')
  await expect(page.locator('.van-toast')).not.toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('makeup-day-editor.png'), fullPage: true, animations: 'disabled' })
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()).violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  await page.getByRole('button', { name: '添加 2 门补课', exact: true }).click()
  await expect(page.locator('#courseWeekSelect')).toHaveValue('4')
  await expect(page.locator('[data-makeup-date="2026-09-26"]')).toHaveCount(2)
  await expect(page.locator('[data-makeup-date="2026-09-26"]').filter({ hasText: '思想概论' })).toContainText('14:40')
  await expect(page.locator('.timetable-week-stage')).toHaveCount(1)
  await expect(page.locator('.van-toast')).not.toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('makeup-timetable.png'), animations: 'disabled' })
  await page.locator('#courseWeekSelect').selectOption('3')
  await expect(page.locator('.timetable-course')).toHaveCount(0)
  await page.getByRole('link', { name: '提醒', exact: true }).click()
  await expect(page.locator('.next-reminders li')).toHaveCount(0)

  // Editing just one makeup and undoing its batch preserve recurring courses.
  await page.getByRole('link', { name: '课表', exact: true }).click()
  await page.getByRole('button', { name: '补课', exact: true }).click()
  await page.locator('.makeup-manage summary').click()
  const item = page.locator('.makeup-manage article').filter({ hasText: '思想概论' })
  await item.getByRole('button', { name: '修改这次', exact: true }).click()
  await page.getByLabel('思想概论上课时间', { exact: true }).fill('14:50')
  await page.getByLabel('思想概论下课时间', { exact: true }).fill('16:30')
  await page.getByRole('button', { name: '保存这次修改', exact: true }).click()
  await expect(page.locator('#courseWeekSelect')).toHaveValue('4')
  await expect(page.locator('.timetable-week-stage')).toHaveCount(1)
  await page.locator('[data-makeup-date="2026-09-26"] .course-content').filter({ hasText: '思想概论' }).click()
  await page.getByText('撤销整批补课', { exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('[data-makeup-date]')).toHaveCount(0)
  await page.locator('#courseWeekSelect').selectOption('3')
  await expect(page.locator('.timetable-course')).toHaveCount(2)
  const saved = await (await page.request.get('http://127.0.0.1:8010/api/courses', { headers })).json()
  expect(saved.map((course: any) => course.id).sort()).toEqual(originals.map(course => course.id).sort())

  // The standalone picker avoids the ordinary course form and recovers from conflicts.
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  await page.getByRole('button', { name: '补课', exact: true }).click()
  await page.getByRole('searchbox', { name: '搜索已有课程' }).fill('思想')
  await expect(page.locator('.makeup-picker button')).toHaveCount(1)
  await page.getByRole('button', { name: /思想概论.*星期一/ }).click()
  await page.getByLabel('补课日期', { exact: true }).fill('2026-09-14')
  await page.getByRole('button', { name: '添加 1 门补课', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('时间冲突')
  await expect(page.getByRole('alert')).toBeInViewport()
  await page.getByLabel('补课日期', { exact: true }).fill('2026-09-20')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: '改地点', exact: true }).click()
  await page.getByLabel('思想概论补课地点').fill('教4-503')
  await expect(page.locator('.van-toast')).not.toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('makeup-single-editor.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '添加 1 门补课', exact: true }).click()
  await expect(page.locator('[data-makeup-date="2026-09-20"]')).toContainText('503')
  await expect(page.locator('[data-makeup-date="2026-09-20"]')).toContainText('14:30')
})
